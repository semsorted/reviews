/** Every business gets a set of faint drawings: its own type first, then its group, then a friendly general set. */
export function artFor(category: string, group: string | null): PosterArt {
  if (FASHION_TYPES.has(category)) return "fashion";
  if (TECH_TYPES.has(category)) return "tech";
  return (group && GROUP_ART[group]) || "general";
}

